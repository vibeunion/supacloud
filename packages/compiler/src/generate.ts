/** Keep status-family spelling stable across generated artifacts. */
function normalizedResponseEntries(
  responses: Readonly<Record<string | number, string>> | undefined,
): Array<[string, string]> {
  if (!responses) return [];
  const seen = new Map<string, string>();
  const result: Array<[string, string]> = [];
  for (const [selector, symbol] of Object.entries(responses)) {
    const family = /^([1-5])(?:xx|XX)$/.exec(selector);
    const normalized = family ? `${family[1]}XX` : selector;
    const previous = seen.get(normalized);
    if (previous !== undefined) {
      throw new TypeError(
        `Duplicate response selectors "${previous}" and "${selector}" resolve to "${normalized}".`,
      );
    }
    seen.set(normalized, selector);
    result.push([normalized, symbol]);
  }
  return result;
}

