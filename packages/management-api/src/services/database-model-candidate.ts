export interface DatabaseModelColumn {
  readonly name: string;
  readonly dataType: string;
  readonly udtName: string;
  readonly nullable: boolean;
  readonly defaultExpression: string | null;
}

export interface DatabaseModelForeignKey {
  readonly column: string;
  readonly foreignSchema: string;
  readonly foreignTable: string;
  readonly foreignColumn: string;
}

export interface DatabaseModelTable {
  readonly schema: string;
  readonly name: string;
  readonly columns: readonly DatabaseModelColumn[];
  readonly primaryKey: readonly string[];
  readonly foreignKeys: readonly DatabaseModelForeignKey[];
}

export interface DatabaseModelEnum {
  readonly schema: string;
  readonly name: string;
  readonly values: readonly string[];
}

export interface DatabaseModelCatalog {
  readonly schemas: readonly string[];
  readonly tables: readonly DatabaseModelTable[];
  readonly enums: readonly DatabaseModelEnum[];
  readonly policyCount: number;
}

export interface DatabaseModelCandidate {
  readonly schema: "supacloud.model-candidate.v1";
  readonly candidate: string;
  readonly warnings: readonly string[];
  readonly catalog: { readonly schemas: readonly string[]; readonly tables: number; readonly enums: number; readonly policies: number };
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function identifier(value: string, fallback: string): string {
  const words = value.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = words.map(word => word[0]!.toUpperCase() + word.slice(1)).join("");
  const result = joined || fallback;
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(result) ? result : `_${result}`;
}

function fieldIdentifier(value: string): string {
  const words = value.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const first = words[0] ?? "field";
  const result = first.toLowerCase() + words.slice(1).map(word => word[0]!.toUpperCase() + word.slice(1)).join("");
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(result) ? result : `_${result}`;
}

function scalarType(column: DatabaseModelColumn): string {
  const type = column.udtName.toLowerCase();
  const dataType = column.dataType.toLowerCase();
  const array = dataType === "array" || type.startsWith("_");
  const base = type.replace(/^_/, "");
  const scalar = base === "bool" ? "Boolean"
    : ["int2", "int4"].includes(base) ? "Int"
      : ["int8", "numeric", "decimal", "float4", "float8"].includes(base) ? "Decimal"
        : ["date", "timestamp", "timestamptz", "time", "timetz"].includes(base) ? "DateTime"
          : ["json", "jsonb"].includes(base) ? "Json"
            : base === "bytea" ? "Bytes"
              : "String";
  return array ? `${scalar}[]` : scalar;
}

function defaultAttribute(expression: string | null): string {
  if (!expression) return "";
  const normalized = expression.trim();
  if (/^nextval\(/i.test(normalized) || /^(?:CURRENT_TIMESTAMP|now\(\))/i.test(normalized)) return "";
  if (/^(?:true|false)$/i.test(normalized)) return ` @default(${normalized.toLowerCase()})`;
  if (/^-?\d+(?:\.\d+)?$/.test(normalized)) return ` @default(${normalized})`;
  const text = normalized.match(/^'((?:[^']|'')*)'(?:::[A-Za-z0-9_." ]+)?$/);
  return text ? ` @default(${quote(text[1]!.replaceAll("''", "'"))})` : "";
}

export function renderDatabaseModelCandidate(catalog: DatabaseModelCatalog): DatabaseModelCandidate {
  const warnings: string[] = [];
  const lines = [
    "// Generated by SupaCloud Management API. Review before promotion.",
    "datasource db {",
    "  provider = \"postgresql\"",
    "  url = env(\"DATABASE_URL\")",
    "}",
    "",
    "plugin policy {",
    "  provider = \"@zenstackhq/plugin-policy\"",
    "}",
    "",
  ];

  for (const item of catalog.enums) {
    lines.push(`enum ${identifier(item.name, "Enum")} {`, ...item.values.map(value => `  ${identifier(value, "Value")}`), "}", "");
  }

  for (const table of catalog.tables) {
    const model = identifier(table.name, "Model");
    lines.push(`model ${model} {`);
    const seen = new Set<string>();
    for (const column of table.columns) {
      const field = fieldIdentifier(column.name);
      if (seen.has(field)) {
        warnings.push(`Skipped duplicate generated field ${table.schema}.${table.name}.${column.name}`);
        continue;
      }
      seen.add(field);
      const mapped = field === column.name ? "" : ` @map(${quote(column.name)})`;
      const optional = column.nullable && !table.primaryKey.includes(column.name) ? "?" : "";
      const primary = table.primaryKey.length === 1 && table.primaryKey[0] === column.name ? " @id" : "";
      lines.push(`  ${field} ${scalarType(column)}${optional}${primary}${mapped}${defaultAttribute(column.defaultExpression)}`);
    }
    if (table.primaryKey.length > 1) {
      lines.push(`  @@id([${table.primaryKey.map(fieldIdentifier).join(", ")}])`);
    }
    if (model !== table.name) {
      lines.push(`  @@map(${quote(table.name)})`);
    }
    lines.push("}", "");
    if (table.foreignKeys.length) warnings.push(`Foreign keys for ${table.schema}.${table.name} require relationship review before promotion`);
  }

  if (catalog.policyCount > 0) warnings.push(`${catalog.policyCount} PostgreSQL policies were detected; relationship and policy rules require explicit review`);
  if (catalog.tables.length === 0) warnings.push("No tables were found in the selected schemas");
  return {
    schema: "supacloud.model-candidate.v1",
    candidate: lines.join("\n") + "\n",
    warnings,
    catalog: { schemas: catalog.schemas, tables: catalog.tables.length, enums: catalog.enums.length, policies: catalog.policyCount },
  };
}
