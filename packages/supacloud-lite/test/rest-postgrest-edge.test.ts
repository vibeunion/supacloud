import { describe, expect, test } from 'bun:test'
import { createLiteBackend } from '../src/index.js'
import { testTimeout } from './helpers/timeouts.js'

const migration = {
  name: '20261026000000_edge_items',
  sql: `
    create table public.edge_items (
      id bigint generated by default as identity primary key,
      name text not null
    );
    grant all on public.edge_items to service_role;
    grant all on sequence public.edge_items_id_seq to service_role;
  `,
}

async function request(
  backend: Awaited<ReturnType<typeof createLiteBackend>>,
  path: string,
  init: RequestInit = {},
) {
  return backend.fetch(`http://local${path}`, {
    ...init,
    headers: {
      apikey: backend.serviceRoleKey,
      authorization: `Bearer ${backend.serviceRoleKey}`,
      'content-type': 'application/json',
      ...init.headers,
    },
  })
}

describe('PostgREST edge semantics', () => {
  test('supports planned and estimated count strategies', async () => {
    const backend = await createLiteBackend({ jwtSecret: 'x'.repeat(64), vaultKey: 'y'.repeat(64), migrations: [migration], log: () => {} })
    try {
      const inserted = await request(backend, '/rest/v1/edge_items', {
        method: 'POST',
        headers: { prefer: 'return=minimal' },
        body: JSON.stringify([{ name: 'one' }, { name: 'two' }, { name: 'three' }]),
      })
      expect(inserted.status).toBe(201)

      for (const strategy of ['planned', 'estimated']) {
        const response = await request(backend, '/rest/v1/edge_items?select=*', {
          headers: { prefer: `count=${strategy}` },
        })
        expect([200, 206]).toContain(response.status)
        const range = response.headers.get('content-range')
        expect(range).toMatch(/^\d+-\d+\/\d+$/)
        // The aggregate node of count(*) always reports one output row; the estimate must come from its input.
        expect(Number(range!.split('/')[1])).toBeGreaterThan(1)
      }

      await backend.db.exec('analyze public.edge_items')
      const estimated = await request(backend, '/rest/v1/edge_items?select=*', {
        headers: { prefer: 'count=estimated' },
      })
      expect(estimated.headers.get('content-range')).toBe('0-2/3')
      const planned = await request(backend, '/rest/v1/edge_items?select=*', {
        headers: { prefer: 'count=planned' },
      })
      expect(Number(planned.headers.get('content-range')!.split('/')[1])).toBeGreaterThan(1)

      const exact = await request(backend, '/rest/v1/edge_items?select=*', {
        headers: { prefer: 'count=exact' },
      })
      expect(exact.headers.get('content-range')).toBe('0-2/3')
    } finally {
      await backend.close()
    }
  }, testTimeout(30_000))

  test('rolls back successful mutations while preserving the response', async () => {
    const backend = await createLiteBackend({ jwtSecret: 'x'.repeat(64), vaultKey: 'y'.repeat(64), migrations: [migration], log: () => {} })
    try {
      const committed = await request(backend, '/rest/v1/edge_items', {
        method: 'POST',
        headers: { prefer: 'return=representation' },
        body: JSON.stringify({ name: 'kept' }),
      })
      expect(committed.status).toBe(201)
      expect(await committed.json()).toEqual([{ id: 1, name: 'kept' }])

      const rolledBack = await request(backend, '/rest/v1/edge_items', {
        method: 'POST',
        headers: { prefer: 'return=representation,tx=rollback' },
        body: JSON.stringify({ name: 'rolled back' }),
      })
      expect(rolledBack.status).toBe(201)
      expect(await rolledBack.json()).toEqual([{ id: 2, name: 'rolled back' }])

      const list = await request(backend, '/rest/v1/edge_items?select=*', {
        headers: { prefer: 'count=exact' },
      })
      expect(list.headers.get('content-range')).toBe('0-0/1')
      expect(await list.json()).toEqual([{ id: 1, name: 'kept' }])

      const updated = await request(backend, '/rest/v1/edge_items?id=eq.1', {
        method: 'PATCH',
        headers: { prefer: 'return=representation,tx=rollback' },
        body: JSON.stringify({ name: 'temporary' }),
      })
      expect(updated.status).toBe(200)
      expect(await updated.json()).toEqual([{ id: 1, name: 'temporary' }])

      const after = await request(backend, '/rest/v1/edge_items?select=*')
      expect(await after.json()).toEqual([{ id: 1, name: 'kept' }])
    } finally {
      await backend.close()
    }
  }, testTimeout(30_000))
})
