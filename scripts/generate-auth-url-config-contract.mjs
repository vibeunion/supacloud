import { readFileSync, writeFileSync } from "node:fs";

for (const [sourcePath, targetName] of [
  ["contracts/auth-url-config.ts", "auth-url-config.ts"],
  ["utils/auth-url-config.ts", "auth-url-validation.ts"],
]) {
  const source = new URL(`../packages/management-api/src/${sourcePath}`, import.meta.url);
  const target = new URL(`../packages/web-console/src/lib/generated/${targetName}`, import.meta.url);
  const generated = "// Generated by scripts/generate-auth-url-config-contract.mjs. Do not edit.\n"
    + readFileSync(source, "utf8").replace('"../contracts/auth-url-config"', '"./auth-url-config"');
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== generated) {
      throw new Error("Auth URL contracts are stale. Run node scripts/generate-auth-url-config-contract.mjs");
    }
  } else {
    writeFileSync(target, generated);
  }
}
