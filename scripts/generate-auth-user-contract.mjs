import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../packages/management-api/src/contracts/auth-user-mutations.ts", import.meta.url);
const target = new URL("../packages/web-console/src/lib/generated/auth-user-mutations.ts", import.meta.url);
const generated = "// Generated by scripts/generate-auth-user-contract.mjs. Do not edit.\n"
  + readFileSync(source, "utf8");

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) {
    throw new Error("Auth user contracts are stale. Run node scripts/generate-auth-user-contract.mjs");
  }
} else {
  writeFileSync(target, generated);
}
console.log(`Auth user contracts synchronized: ${fileURLToPath(target)}`);
