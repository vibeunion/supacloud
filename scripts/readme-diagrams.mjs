import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const assetDir = 'docs/assets/readme';
export const locales = ['en', 'zh-CN'];
export const names = ['overview', 'build-runtime', 'project-storage'];
export const escapeXml = (text) => String(text).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));

export function validateLabels(labels) {
  const signature = value => {
    if (Array.isArray(value)) return value.map(signature);
    if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(k => [k, signature(value[k])]));
    if (typeof value !== 'string' || !value.trim()) throw new Error('Expected non-empty text');
    return 'text';
  };
  if (JSON.stringify(Object.keys(labels).sort()) !== JSON.stringify([...locales].sort())) throw new Error('Expected en and zh-CN');
  for (const locale of locales) {
    if (JSON.stringify(Object.keys(labels[locale]).sort()) !== JSON.stringify([...names].sort())) throw new Error('Unexpected diagram names');
  }
  if (JSON.stringify(signature(labels.en)) !== JSON.stringify(signature(labels['zh-CN']))) throw new Error('Locale structure mismatch');
  for (const locale of locales) for (const name of names) {
    const t = labels[locale][name];
    for (const key of ['title', 'description', 'subtitle', 'note']) if (typeof t[key] !== 'string') throw new Error(`Missing ${key}`);
    const count = {overview:3, 'build-runtime':6, 'project-storage':5}[name];
    if (!Array.isArray(t.cards) || t.cards.length !== count) throw new Error('Wrong card count');
    for (const card of t.cards) if (!Array.isArray(card) || card.length < 2 || card.length > 5 || !card.every(s => typeof s === 'string')) throw new Error('Invalid card');
  }
}

export function renderDiagram(name, locale, labels) {
  validateLabels(labels);
  if (!names.includes(name) || !locales.includes(locale)) throw new Error('Unknown diagram or locale');
  const t = labels[locale][name];
  const height = name === 'project-storage' ? 760 : 720;
  const out = [
    '<!-- Generated by scripts/readme-diagrams.mjs; edit labels.json and the shared renderer. -->',
    `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="${height}" viewBox="0 0 1200 ${height}" role="img" aria-labelledby="title description" xml:lang="${locale}">`,
    `<title id="title">${escapeXml(t.title)}</title><desc id="description">${escapeXml(t.description)}</desc>`,
    '<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0 L8 4 L0 8 Z" fill="#526579"/></marker></defs>',
    '<style>text{font-family:Arial,"Noto Sans CJK SC","Microsoft YaHei",sans-serif;fill:#162B40}.title{font-size:34px;font-weight:700}.subtitle{font-size:21px;fill:#526579}.heading{font-size:23px;font-weight:700}.body{font-size:20px;fill:#334C63}.lane{font-size:16px;font-weight:700;fill:#37675F;letter-spacing:1px}</style>',
    `<rect width="1200" height="${height}" fill="#FFFFFF"/>`
  ];
  const text = (x,y,value,cls='body') => out.push(`<text x="${x}" y="${y}" class="${cls}">${escapeXml(value)}</text>`);
  const card = (x,y,w,h,lines,accent=false) => {
    out.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="16" fill="${accent ? '#EDF8F5' : '#F5F8FB'}" stroke="#D5E0E9"/>`);
    text(x+24,y+40,lines[0],'heading');
    lines.slice(1).forEach((line,i) => text(x+24,y+78+i*30,line));
  };
  const arrow = d => out.push(`<path d="${d}" fill="none" stroke="#526579" stroke-width="2" marker-end="url(#arrow)"/>`);
  text(48,40,'SUPACLOUD','lane'); text(48,86,t.title,'title'); text(48,124,t.subtitle,'subtitle');
  if (name === 'overview') {
    card(48,160,1104,184,t.cards[0],true);
    text(48,392,t.lane,'lane');
    card(48,420,536,224,t.cards[1]); card(616,420,536,224,t.cards[2]);
  } else if (name === 'build-runtime') {
    text(48,168,t.compileLane,'lane'); text(48,414,t.runtimeLane,'lane');
    for (let i=0;i<3;i++) card(48+i*392,190,320,168,t.cards[i],i===1);
    for (let i=0;i<3;i++) card(48+i*392,442,320,168,t.cards[3+i],i===2);
    arrow('M368 274 H430'); arrow('M760 274 H822'); arrow('M992 358 V432');
    arrow('M832 526 H770'); arrow('M440 526 H378');
  } else {
    card(48,330,300,166,t.cards[0]); card(412,312,306,202,t.cards[1],true);
    for (let i=0;i<3;i++) card(814,170+i*176,338,142,t.cards[2+i]);
    arrow('M348 413 H402');
    // Separate project routes, deliberately no backend-to-backend/failover edges.
    arrow('M718 413 H766 V241 H804'); arrow('M718 413 H766 V417 H804'); arrow('M718 413 H766 V593 H804');
  }
  text(48,height-30,t.note);
  return out.join('\n') + '\n</svg>\n';
}

export function generate(check=false, repo=root) {
  const labels = JSON.parse(readFileSync(resolve(repo,assetDir,'labels.json'),'utf8'));
  for (const name of names) for (const locale of locales) {
    const path = resolve(repo,assetDir,`${name}.${locale}.svg`);
    const expected = renderDiagram(name,locale,labels);
    if (check) { if (readFileSync(path,'utf8') !== expected) throw new Error(`Stale diagram: ${path}`); }
    else writeFileSync(path,expected);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/readme-diagrams.mjs [--check]');
  generate(process.argv.includes('--check'));
  console.log('README diagrams: 6 ' + (process.argv.includes('--check') ? 'verified' : 'generated'));
}
